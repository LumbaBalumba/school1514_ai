def execute_example(source: str, namespace: dict) -> tuple[object, str]:
    """Emulate a notebook cell, including its final expression."""
    tree = ast.parse(source)
    output = io.StringIO()
    result = None
    with redirect_stdout(output):
        if tree.body and isinstance(tree.body[-1], ast.Expr):
            statements = ast.Module(body=tree.body[:-1], type_ignores=[])
            exec(compile(statements, "lesson_example", "exec"), namespace)
            result = eval(
                compile(ast.Expression(tree.body[-1].value), "lesson_result", "eval"),
                namespace,
            )
        else:
            exec(compile(tree, "lesson_example", "exec"), namespace)
    return result, output.getvalue().strip()


def render_result(result: object, stdout: str, target: Path) -> str:
    if isinstance(result, pd.Series):
        result = result.to_frame()
    if isinstance(result, pd.DataFrame):
        frame = result.copy()
        values = frame.map(str)
        fig, ax = plt.subplots(figsize=(5.2, 3.3))
        ax.axis("off")
        table = ax.table(
            cellText=values.values,
            colLabels=frame.columns,
            rowLabels=frame.index,
            loc="center",
            cellLoc="left",
        )
        table.auto_set_font_size(False)
        table.set_fontsize(10 if len(frame.columns) >= 4 else 12)
        table.scale(1, 1.9)
        index_width = 0.22 if frame.index.name else 0.07
        if frame.index.name:
            corner = table.add_cell(
                0,
                -1,
                width=index_width,
                height=table[0, 0].get_height(),
                text=str(frame.index.name),
                loc="center",
            )
            corner.set_fontsize(12)
        for (row, column), cell in table.get_celld().items():
            cell.set_edgecolor("#d4dae2")
            if column == -1:
                cell.set_width(index_width)
                cell.set_text_props(ha="center")
            if row == 0:
                cell.set_facecolor("#e8eef7")
                cell.set_text_props(weight="bold")
        text = frame.to_string()
    else:
        text = stdout or str(result)
        fig, ax = plt.subplots(figsize=(5.2, 3.3))
        ax.axis("off")
        ax.text(
            0.02,
            0.55,
            text,
            va="center",
            ha="left",
            fontsize=12,
            family="DejaVu Sans Mono",
        )
    fig.savefig(target.with_suffix(".pdf"), bbox_inches="tight")
    fig.savefig(target.with_suffix(".png"), dpi=160, bbox_inches="tight")
    plt.close(fig)
    return text


def tex_escape(text: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
        "°": r"\ensuremath{^\circ}",
    }
    return "".join(replacements.get(char, char) for char in text)


def execute_notebook(path: Path) -> None:
    notebook = nbf.read(path, as_version=4)
    manager = KernelManager(kernel_name="python3")
    manager.kernel_spec.argv = [
        sys.executable,
        "-m",
        "ipykernel_launcher",
        "-f",
        "{connection_file}",
    ]
    try:
        NotebookClient(
            notebook,
            km=manager,
            timeout=120,
            resources={"metadata": {"path": str(path.parent)}},
        ).execute()
    finally:
        if manager.has_kernel:
            manager.shutdown_kernel(now=True)
    nbf.write(notebook, path)


